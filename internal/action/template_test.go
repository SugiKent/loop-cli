// TestAnswerTemplateUsesLatestQuestionComment は人への問いを末尾から探すことを検証する。
// 後ろに人のコメントがあっても routine の問いを採り、それより古いコメントは使わない。
func TestAnswerTemplateUsesLatestQuestionComment(t *testing.T) {
	comments := append(exampleIssueComments(t),
		aiComment("## Q1. 方式をどうするか\n- 選択肢 B（推奨）: 案 2"),
		humanComment("## Q1. 人が書いた見出し\n- 選択肢 A（推奨）: x"),
	)
	want := "> ## Q1. 方式をどうするか\n> - 選択肢 B（推奨）: 案 2\n\nQ1: B"
	if got := AnswerTemplate(comments); got != want {
		t.Errorf("AnswerTemplate = %q, want %q", got, want)
	}
}

// TestAnswerTemplateReplacesInlineMarker は行の途中のマーカーを置き換えて残すことを見る。
// 行ごと落とすと質問文が消えたまま回答行だけが残り、投稿もできなくなる。
func TestAnswerTemplateReplacesInlineMarker(t *testing.T) {
	got := AnswerTemplate([]model.Comment{aiComment(
		"<!-- routine -->\n## Q1. 先頭に <!-- routine --> を入れるか\n- 選択肢 A（推奨）: 入れない")})

	if !strings.Contains(got, "> ## Q1. 先頭に [routine マーカー] を入れるか") {
		t.Errorf("AnswerTemplate = %q, want 置き換えた質問行を含む", got)
	}
	if !strings.HasSuffix(got, "\nQ1: A") {
		t.Errorf("AnswerTemplate = %q, want Q1: A で終わる", got)
	}
	if HasRoutineMarker(got) {
		t.Errorf("AnswerTemplate = %q, want マーカーを含まない（含むと投稿できない）", got)
	}

	escaped := AnswerTemplate([]model.Comment{aiComment(
		"&lt;!-- routine --&gt;\n## Q1. 方式をどうするか\n- 選択肢 A（推奨）: 案 1")})
	if HasRoutineMarker(escaped) {
		t.Errorf("AnswerTemplate = %q, want エスケープ済みのマーカーも含まない", escaped)
	}
}
